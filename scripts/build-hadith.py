def sections(path, titles):
    with open(path) as f:
        d = json.load(f)
    counts = {}
    for h in d['hadiths']:
        if h['text'].strip():
            b = h['reference']['book']
            counts[b] = counts.get(b, 0) + 1
    out = []
    for n in sorted(counts):
        if n not in titles:
            continue
        kk, ru = titles[n]
        out.append(dict(n=n, kk=kk, ru=ru, count=counts[n]))
    return out


def main():
    books = [
        dict(id='bukhari', kk='Сахих әл-Бұхари', ru='Сахих аль-Бухари', sections=sections(sys.argv[1], BUKHARI)),
        dict(id='muslim', kk='Сахих Муслим', ru='Сахих Муслим', sections=sections(sys.argv[2], MUSLIM)),
    ]
    out = os.path.join(os.path.dirname(__file__), '..', 'assets', 'hadith', 'books.json')
    with open(out, 'w') as f:
        json.dump(books, f, ensure_ascii=False, indent=1)
    for b in books:
        print(b['id'], len(b['sections']), sum(s['count'] for s in b['sections']))


if __name__ == '__main__':
    main()
