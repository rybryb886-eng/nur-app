"""Builds bundled Quran data (assets/quran) from fawazahmed0/quran-api editions.

Usage: python3 scripts/build-quran.py <dir with downloaded *.json editions>
Needs: ara-quranuthmanihaf.json, ara-quran-la1.json, kaz-khalifahaltaich.json,
       rus-elmirkuliev.json, info.json
"""
import json, os, re, sys

SRC = sys.argv[1]
OUT = os.path.join(os.path.dirname(__file__), '..', 'assets', 'quran')

NAMES = """Фатиха|Бақара|Әли Имран|Ниса|Мәида|Әнғам|Ағраф|Әнфал|Тәубе|Юнус|Һуд|Юсуф|Рағд|Ибраһим|Хижр|Нахл|Исра|Кәһф|Мәриям|Таһа|Әнбия|Хаж|Мүминун|Нұр|Фұрқан|Шұғара|Нәміл|Қасас|Анкабут|Рум|Лұқман|Сәжде|Ахзаб|Сәба|Фатыр|Ясин|Саффат|Сад|Зұмар|Ғафир|Фуссилат|Шура|Зухруф|Духан|Жәсия|Ахқаф|Мұхаммед|Фатх|Хұжырат|Қаф|Зәрият|Тур|Нәжм|Қамар|Рахман|Уақиға|Хадид|Мүжәдәлә|Хашр|Мүмтахина|Саф|Жұма|Мұнафиқун|Тағабун|Талақ|Тахрим|Мүлік|Қалам|Хаққа|Мағариж|Нұх|Жын|Мүззәммил|Мүддәссир|Қиямет|Инсан|Мурсалат|Нәбә|Нәзиғат|Абаса|Тәкуир|Инфитар|Мұтаффифин|Иншиқақ|Буруж|Тариқ|Ағла|Ғашия|Фәжр|Бәләд|Шәмс|Ләйл|Духа|Шарх|Тин|Ғалақ|Қадір|Бәййина|Зілзала|Ғадият|Қариға|Тәкәсур|Аср|Һумаза|Фил|Құрайыш|Мағун|Кәусар|Кафирун|Наср|Мәсәд|Ықылас|Фәләқ|Нас""".split('|')
assert len(NAMES) == 114

DIGRAPHS = [('yaa', 'я'), ('uwa', 'уа'), ('uwi', 'уи'), ('kh', 'х'), ('gh', 'Ɣ'), ('sh', 'ш'), ('th', 'с'), ('dh', 'з'),
            ('aa', 'а'), ('ee', 'и'), ('oo', 'у'), ('ya', 'я'), ('yu', 'ю')]
SINGLE = dict(a='а', i='и', u='у', e='е', o='о', b='б', t='т', j='ж', h='х', d='д',
              r='р', z='з', s='с', f='ф', q='қ', k='к', l='л', m='м', n='н', w='у',
              y='й', g='г', c='к', x='кс')
# 'Ɣ' marks gh (غ); the apostrophe marks ain (ع).
KK = {'Ɣ': 'ғ', "'": 'ғ'}
RU = {'Ɣ': 'г', 'қ': 'к', 'ж': 'дж'}


def to_cyr(text, lang):
    """Approximate Latin -> Cyrillic transliteration of the la1 edition."""
    s = text.replace('lyyaaka', 'iyyaaka')
    s = re.sub(r'(aa|ee|oo)\1*[aeo]*', r'\1', s)
    out, i = [], 0
    while i < len(s):
        ch = s[i]
        up = ch.isupper()
        rep = None
        for k, v in DIGRAPHS:
            if s[i:i + len(k)].lower() == k:
                rep, i = v, i + len(k)
                break
        if rep is None:
            c = ch.lower()
            if c in SINGLE:
                rep = SINGLE[c]
            else:
                rep = ch
            i += 1
        table = RU if lang == 'ru' else KK
        rep = ''.join(table.get(x, x) for x in rep)
        out.append(rep[:1].upper() + rep[1:] if up else rep)
    r = ''.join(out)
    r = re.sub(r"(ғ|')([А-ЯӘ])", lambda m: m.group(1).upper() + m.group(2).lower(), r)
    # Allah: kk "Аллаһ", ru "Аллах"
    if lang == 'kk':
        r = re.sub(r'ллах', 'ллаһ', r)
        r = re.sub(r'ЛЛАХ', 'ЛЛАҺ', r)
    return r


def load(name):
    with open(os.path.join(SRC, name)) as f:
        return json.load(f)['quran']


def by_chapter(rows):
    m = {}
    for v in rows:
        m.setdefault(v['chapter'], []).append(v['text'])
    return m


def main():
    ar = by_chapter(load('ara-quranuthmanihaf.json'))
    la = by_chapter(load('ara-quran-la1.json'))
    kk = by_chapter(load('kaz-khalifahaltaich.json'))
    ru = by_chapter(load('rus-elmirkuliev.json'))
    with open(os.path.join(SRC, 'info.json')) as f:
        info = json.load(f)['chapters']

    os.makedirs(os.path.join(OUT, 's'), exist_ok=True)
    meta = []
    for ch in info:
        n = ch['chapter']
        count = len(ar[n])
        assert len(la[n]) == len(kk[n]) == len(ru[n]) == count, n
        meta.append(dict(n=n, name=NAMES[n - 1], lat=ch['name'], ar=ch['arabicname'],
                         ayahs=count, mecca=ch['revelation'] == 'Mecca'))
        surah = dict(ar=ar[n], lat=la[n],
                     cyrKk=[to_cyr(t, 'kk') for t in la[n]],
                     cyrRu=[to_cyr(t, 'ru') for t in la[n]],
                     kk=kk[n], ru=ru[n])
        with open(os.path.join(OUT, 's', f'{n:03}.json'), 'w') as f:
            json.dump(surah, f, ensure_ascii=False, separators=(',', ':'))
    with open(os.path.join(OUT, 'meta.json'), 'w') as f:
        json.dump(meta, f, ensure_ascii=False, separators=(',', ':'))

    lines = ['// Generated by scripts/build-quran.py. Do not edit.',
             'export function loadSurahData(n: number) {', '  switch (n) {']
    for n in range(1, 115):
        lines.append(f"    case {n}: return require('./s/{n:03}.json');")
    lines += ['    default: throw new Error(`Unknown surah ${n}`);', '  }', '}', '']
    with open(os.path.join(OUT, 'index.ts'), 'w') as f:
        f.write('\n'.join(lines))


if __name__ == '__main__':
    main()
