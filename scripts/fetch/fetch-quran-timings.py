"""Word timings for Mishary Alafasy's whole-surah recitation (quran.com, reciter 7).

Writes assets/quran/t/NNN.json: {"u": audio url, "v": [[from_ms, to_ms, [word, start, end, ...]], ...]},
one entry per ayah, words numbered from 1. Plus assets/quran/timings.ts mapping surah -> require().
"""
import json
import os
import time
import urllib.request

OUT = "assets/quran/t"
os.makedirs(OUT, exist_ok=True)


def get(url):
    for attempt in range(5):
        try:
            return json.loads(urllib.request.urlopen(url, timeout=60).read())
        except Exception:
            time.sleep(2 ** attempt)
    raise RuntimeError(url)


for n in range(1, 115):
    path = f"{OUT}/{n:03}.json"
    if os.path.exists(path):
        continue
    f = get(f"https://api.qurancdn.com/api/qdc/audio/reciters/7/audio_files?chapter={n}&segments=true")["audio_files"][0]
    verses = sorted(f["verse_timings"], key=lambda v: int(v["verse_key"].split(":")[1]))
    out = {"u": f["audio_url"], "v": []}
    for v in verses:
        flat = []
        for s in v.get("segments") or []:
            if len(s) == 3:
                flat += [int(s[0]), int(s[1]), int(s[2])]
        out["v"].append([int(v["timestamp_from"]), int(v["timestamp_to"]), flat])
    with open(path, "w") as fh:
        json.dump(out, fh, separators=(",", ":"))
    print(n, len(out["v"]))

with open("assets/quran/timings.ts", "w") as fh:
    fh.write("// Generated by scripts/fetch/fetch-quran-timings.py\n")
    fh.write("export type SurahTimings = { u: string; v: [number, number, number[]][] };\n\n")
    fh.write("export function loadTimings(n: number): SurahTimings {\n  switch (n) {\n")
    for n in range(1, 115):
        fh.write(f"    case {n}: return require('./t/{n:03}.json');\n")
    fh.write("    default: throw new Error(`No timings for surah ${n}`);\n  }\n}\n")
