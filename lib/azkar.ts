export function azkar(category: DhikrCategory): Dhikr[] {
  switch (category) {
    case 'morning':
      return [ayatAlKursi(), ...quls(), SAYYID_ISTIGHFAR, BISMILLAH_LA_YADURRU, RADITU, HASBIYALLAH, SUBHANALLAH_100];
    case 'evening':
      return [ayatAlKursi(), ...quls(), SAYYID_ISTIGHFAR, BISMILLAH_LA_YADURRU, RADITU, HASBIYALLAH, AUDHU_KALIMAT];
    case 'afterPrayer':
      return AFTER_PRAYER();
  }
}
